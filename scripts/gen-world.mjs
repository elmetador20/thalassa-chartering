// Generates the dot-matrix world map used by <WorldMap />.
// Emits ONE compact SVG path string (zero-length segments + round linecap =
// thousands of dots in a single DOM node) so the map stays cheap on mobile.
// Output: src/data/worldMapData.ts — static, no runtime map dependency.
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import * as topojson from 'topojson-client';
import { geoEquirectangular, geoContains } from 'd3-geo';

const require = createRequire(import.meta.url);
const topo = JSON.parse(readFileSync(require.resolve('world-atlas/land-110m.json'), 'utf8'));
const land = topojson.feature(topo, topo.objects.land);

const W = 1002;
const H = 440;
const STEP = 6;

// Equirectangular. Vertical offset trims Antarctica and centres the inhabited world.
const projection = geoEquirectangular()
  .scale(W / (2 * Math.PI))
  .translate([W / 2, H / 2 + 42]);

const segs = [];
for (let y = 0; y < H; y += STEP) {
  for (let x = 0; x < W; x += STEP) {
    const inv = projection.invert([x, y]);
    if (!inv) continue;
    const [lon, lat] = inv;
    if (lat < -56 || lat > 80) continue; // trim Antarctica + polar noise
    if (geoContains(land, [lon, lat])) segs.push(`M${x} ${y}h0`);
  }
}

const CITIES = [
  { name: 'London', coords: [-0.1276, 51.5072] },
  { name: 'Dubai', coords: [55.2708, 25.2048] },
  { name: 'Delhi', coords: [77.209, 28.6139] },
  { name: 'Singapore', coords: [103.8198, 1.3521] },
  { name: 'Hong Kong', coords: [114.1694, 22.3193] },
];
const round = (n) => Math.round(n * 10) / 10;
const cities = CITIES.map((c) => {
  const [x, y] = projection(c.coords);
  return { name: c.name, x: round(x), y: round(y) };
});

const out = `// AUTO-GENERATED by scripts/gen-world.mjs — do not edit by hand.
// Source: Natural Earth 110m land (public domain) via the world-atlas package.
// Equirectangular projection baked into a ${W}x${H} viewBox.

export const MAP_W = ${W};
export const MAP_H = ${H};
export const DOT_STEP = ${STEP};

/** Landmass as a single path of zero-length segments.
 *  Render with stroke-linecap="round" and a stroke-width of ~2–3 to get dots. */
export const LAND_DOTS_PATH =
  '${segs.join('')}';

/** Office markers, pre-projected into the same viewBox. */
export const CITY_POINTS: { name: string; x: number; y: number }[] = ${JSON.stringify(cities)};
`;

writeFileSync('src/data/worldMapData.ts', out);
console.log(`dots: ${segs.length}  path chars: ${segs.join('').length}`);
